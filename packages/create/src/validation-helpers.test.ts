import { validateWorldManifest, worldManifestSchema } from "@covel/shared";
import { describe, expect, it } from "vitest";
import {
  EXCLUDED_GENERATED_MANIFEST_KEYS,
  findLoreQualityErrors,
  normalizeGeneratedManifest,
  WORLD_MANIFEST_ROOT_KEYS,
} from "./validation-helpers.js";

function loreWith(content: string): string {
  return `# The Glass City

${content}

1. Repair the broken gate.
2. Find the missing keeper.
3. Stop the coming storm.`;
}

describe("findLoreQualityErrors", () => {
  it.each([
    ["framework", "A technomantic framework binds every tower together."],
    ["model", "The senate follows a social model inherited from its founders."],
    ["cost", "Every ritual carries a terrible cost."],
    ["api", "The oracle Api records each oath."],
    ["test", "The pilgrimage ends with a test of courage."],
    ["prompt", "The sentry took prompt action when the beacon failed."],
    ["cheap", "The dockside tavern serves cheap wine."],
    [
      "software framework",
      "The archive runs on an ancient software framework.",
    ],
    [
      "REST API",
      "The machine-city exposes its laws through a REST API endpoint.",
    ],
    ["Chinese model", "工匠依照城市模型重建了倒塌的钟楼。"],
  ])("allows %s when it belongs to the setting", (_name, content) => {
    expect(findLoreQualityErrors(loreWith(content))).toEqual([]);
  });

  it.each([
    "This world is a test fixture for validation.",
    "This lore is model output generated by an LLM.",
    "The prompt instructions require a generic fantasy setting.",
    "This package uses a cheap LLM generation pipeline.",
    "这是一个低成本快速验证用的世界。",
    "这段世界设定来自模型输出。",
  ])("rejects explicit generation meta wording: %s", (content) => {
    expect(findLoreQualityErrors(loreWith(content))).toContain(
      "WORLD.md contains explicit generation meta wording",
    );
  });
});

describe("obsolete generated dimensions", () => {
  it("leaves obsolete inline dimensions for strict validation to reject", () => {
    const manifest = { id: "plain", dimensions: {} };
    expect(normalizeGeneratedManifest(manifest)).toEqual([]);
    expect(validateWorldManifest(manifest).errors).toEqual(
      expect.arrayContaining([
        expect.objectContaining({
          path: "dimensions",
          message: expect.stringContaining("data/dimensions.yaml"),
        }),
      ]),
    );
  });
});

describe("normalizeGeneratedManifest", () => {
  it("preserves themeMusic and includes every non-excluded key in worldManifestSchema.shape", () => {
    const manifest: Record<string, unknown> = {
      id: "glass-city",
      name: "The Glass City",
      summary: "A city of fragile spires.",
      defaultLocale: "en-US",
      themeMusic: "media/music/theme.mp3",
    };

    expect(normalizeGeneratedManifest(manifest)).toEqual([]);
    expect(manifest.themeMusic).toBe("media/music/theme.mp3");
    expect(validateWorldManifest(manifest).valid).toBe(true);

    const expectedKeys = Object.keys(worldManifestSchema.shape).filter(
      (key) => !EXCLUDED_GENERATED_MANIFEST_KEYS.has(key),
    );
    expect([...WORLD_MANIFEST_ROOT_KEYS].sort()).toEqual(
      [...expectedKeys].sort(),
    );
    expect(WORLD_MANIFEST_ROOT_KEYS.has("themeMusic")).toBe(true);

    const allAllowed = Object.fromEntries(
      expectedKeys.map((key) => [
        key,
        key === "version" ? "1.0.0" : "placeholder",
      ]),
    );
    expect(normalizeGeneratedManifest(allAllowed)).toEqual([]);
    for (const key of expectedKeys) {
      expect(allAllowed).toHaveProperty(key);
    }
  });

  it("still strips excluded generated keys and unknown root fields", () => {
    const manifest: Record<string, unknown> = {
      id: "glass-city",
      cover: "media/gallery/cover.webp",
      accentColor: "#c9a24b",
      unknownField: true,
    };

    expect(normalizeGeneratedManifest(manifest)).toEqual([
      'removed unknown root field "cover"',
      'removed unknown root field "accentColor"',
      'removed unknown root field "unknownField"',
    ]);
    expect(manifest).toEqual({ id: "glass-city" });
  });
});
