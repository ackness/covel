#!/usr/bin/env node
/**
 * Render the author-facing JSON Schemas in `packages/shared/schemas/` as
 * Markdown field tables under `docs/reference/schema/`.
 *
 * The Zod schemas are the only place a field is described. They are exported
 * to JSON Schema by `pnpm --filter @covel/shared generate:schemas`; this script
 * turns that export into reference pages, so the tables cannot drift from the
 * validator.
 *
 *   node scripts/generate-schema-reference.mjs           # write the pages
 *   node scripts/generate-schema-reference.mjs --check   # fail when stale
 */

import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const repoRoot = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const schemaDir = path.join(repoRoot, "packages/shared/schemas");
const outDir = path.join(repoRoot, "docs/reference/schema");

const PAGES = [
  {
    schema: "world-manifest.schema.json",
    page: "world-manifest.md",
    file: "`world.yaml`",
  },
  {
    schema: "world-data.schema.json",
    page: "world-data-descriptor.md",
    file: "`data/world.data.yaml`",
  },
  {
    schema: "world-dimensions.schema.json",
    page: "world-dimensions.md",
    file: "`data/dimensions.yaml`",
  },
  {
    schema: "plugin-manifest.schema.json",
    page: "plugin-manifest.md",
    file: "`PLUGIN.md` frontmatter",
  },
  {
    schema: "runtime-manifest.schema.json",
    page: "runtime-manifest.md",
    file: "`RUNTIME.md` frontmatter",
  },
];

const GENERATED_NOTE =
  "> Generated by `pnpm schemas:generate` from the Zod schemas in `packages/shared/src/schemas/`. Do not edit by hand; change the schema's `.describe()` text instead.";

function isNode(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

/** Follow `$ref` and the single-branch `allOf` Zod wraps references in. */
function resolve(root, node) {
  let current = node;
  for (let hops = 0; hops < 16 && isNode(current); hops += 1) {
    if (typeof current.$ref === "string") {
      current = root.definitions?.[current.$ref.split("/").pop()];
    } else if (Array.isArray(current.allOf) && current.allOf.length === 1) {
      current = current.allOf[0];
    } else break;
  }
  return isNode(current) ? current : {};
}

function isLocaleMap(node) {
  return (
    node.type === "object" &&
    !node.properties &&
    isNode(node.additionalProperties) &&
    node.additionalProperties.type === "string"
  );
}

function literal(value) {
  return `\`${JSON.stringify(value)}\``;
}

/** One-line type summary for the table. */
function typeLabel(root, raw) {
  const node = resolve(root, raw);
  if (Array.isArray(node.enum)) return node.enum.map(literal).join(" or ");
  if (Object.hasOwn(node, "const")) return literal(node.const);
  if (Array.isArray(node.anyOf)) {
    const branches = node.anyOf.map((branch) => resolve(root, branch));
    if (
      branches.length === 2 &&
      branches[0].type === "string" &&
      isLocaleMap(branches[1])
    )
      return "text";
    return [...new Set(branches.map((branch) => typeLabel(root, branch)))].join(
      " or ",
    );
  }
  if (Array.isArray(node.type)) return node.type.join(" or ");
  if (node.type === "array")
    return node.items ? `list of ${typeLabel(root, node.items)}` : "list";
  if (node.type === "object") {
    if (node.properties) return "object";
    if (isNode(node.additionalProperties))
      return `map of ${typeLabel(root, node.additionalProperties)}`;
    return "object";
  }
  return typeof node.type === "string" ? node.type : "any";
}

/** Object shapes reachable from a property, with the path suffix to reach them. */
function nestedObjects(root, raw, suffix = "") {
  const node = resolve(root, raw);
  if (Array.isArray(node.anyOf))
    return node.anyOf.flatMap((branch) => nestedObjects(root, branch, suffix));
  if (node.type === "array" && node.items)
    return nestedObjects(root, node.items, `${suffix}[]`);
  if (node.type === "object") {
    if (node.properties) return [{ suffix, node }];
    if (isNode(node.additionalProperties))
      return nestedObjects(root, node.additionalProperties, `${suffix}.*`);
  }
  return [];
}

function cell(text) {
  return String(text).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function describeProperty(raw) {
  const parts = [];
  if (typeof raw.description === "string") parts.push(raw.description);
  if (Array.isArray(raw.examples) && raw.examples.length > 0)
    parts.push(`Example: ${raw.examples.map(literal).join(", ")}.`);
  if (Object.hasOwn(raw, "default"))
    parts.push(`Default: ${literal(raw.default)}.`);
  return parts.join(" ");
}

function renderSections(root) {
  const sections = [];
  const rendered = new Map();
  // Depth-first, so a nested object follows the table that introduces it.
  function renderSection(title, sectionPath, node) {
    const seenAt = rendered.get(node);
    if (seenAt !== undefined) {
      sections.push(`## ${title}\n\nSame fields as ${seenAt}.`);
      return;
    }
    rendered.set(node, title);
    const required = new Set(node.required ?? []);
    const children = [];
    const rows = Object.entries(node.properties).map(([key, raw]) => {
      const childPath = sectionPath ? `${sectionPath}.${key}` : key;
      children.push(...sectionsFor(nestedObjects(root, raw), childPath));
      return `| \`${key}\` | ${cell(typeLabel(root, raw))} | ${required.has(key) ? "yes" : "no"} | ${cell(describeProperty(raw))} |`;
    });
    sections.push(
      [
        `## ${title}`,
        "",
        "| Field | Type | Required | Description |",
        "| --- | --- | --- | --- |",
        ...rows,
      ].join("\n"),
    );
    for (const child of children)
      renderSection(child.title, child.path, child.node);
  }
  // A union of object shapes yields several tables for one path; number them
  // so the headings (and their anchors) stay distinct.
  function sectionsFor(nested, basePath) {
    const total = new Map();
    for (const { suffix } of nested)
      total.set(suffix, (total.get(suffix) ?? 0) + 1);
    const index = new Map();
    return nested.map(({ suffix, node }) => {
      const sectionPath = `${basePath}${suffix}`.replace(/^\./, "");
      const position = (index.get(suffix) ?? 0) + 1;
      index.set(suffix, position);
      const label = sectionPath ? `\`${sectionPath}\`` : "Top-level fields";
      return {
        path: sectionPath,
        node,
        title:
          total.get(suffix) > 1
            ? `${label} (form ${position} of ${total.get(suffix)})`
            : label,
      };
    });
  }
  // The root may itself be a map (a dimensions file), so start from its shapes.
  for (const section of sectionsFor(nestedObjects(root, root), ""))
    renderSection(section.title, section.path, section.node);
  return sections;
}

function renderPage(page, root) {
  return [
    `# ${String(root.title)
      .replace(/^Covel /, "")
      .replace(/^./, (c) => c.toUpperCase())}`,
    "",
    GENERATED_NOTE,
    "",
    root.description,
    "",
    `JSON Schema: [\`${page.schema}\`](../../../packages/shared/schemas/${page.schema}).`,
    "",
    "In the path headings below, `[]` is a list item and `.*` is a map value.",
    "",
    ...renderSections(root).flatMap((section) => [section, ""]),
  ].join("\n");
}

function renderIndex(pages) {
  return [
    "# Schema reference",
    "",
    GENERATED_NOTE,
    "",
    "Field tables for every file a world or plugin author writes. Concepts, boundaries and reasons stay in the hand-written reference pages; legal fields live here.",
    "",
    "| File | Fields | JSON Schema |",
    "| --- | --- | --- |",
    ...pages.map(
      ({ page, root }) =>
        `| ${page.file} | [${String(root.title).replace(/^Covel /, "")}](${page.page}) | [\`${page.schema}\`](../../../packages/shared/schemas/${page.schema}) |`,
    ),
    "",
    "## Editor support",
    "",
    "Editors that use the YAML language server show completion, hover text and inline errors once a file names its schema on the first line:",
    "",
    "```yaml",
    "# yaml-language-server: $schema=../../packages/shared/schemas/world-manifest.schema.json",
    "```",
    "",
    "The path is relative to the file. The bundled worlds under `worlds/` use the form above for `world.yaml`.",
    "",
    "## What the JSON Schema does not check",
    "",
    "The Zod schemas stay authoritative. Cross-field rules, uniqueness rules and the dimension value subset are enforced only by `pnpm validate:world` and `pnpm validate:plugin`.",
    "",
  ].join("\n");
}

async function build() {
  const options = (await prettier.resolveConfig(outDir)) ?? {};
  const pages = [];
  for (const page of PAGES) {
    const root = JSON.parse(
      await readFile(path.join(schemaDir, page.schema), "utf8"),
    );
    pages.push({ page, root });
  }
  const files = new Map();
  for (const { page, root } of pages)
    files.set(page.page, renderPage(page, root));
  files.set("README.md", renderIndex(pages));
  for (const [name, content] of files)
    files.set(
      name,
      await prettier.format(content, { ...options, parser: "markdown" }),
    );
  return files;
}

const check = process.argv.includes("--check");
const files = await build();
const stale = [];
for (const [name, content] of files) {
  const target = path.join(outDir, name);
  const current = await readFile(target, "utf8").catch(() => undefined);
  if (current === content) continue;
  stale.push(path.relative(repoRoot, target));
  if (!check) {
    await mkdir(outDir, { recursive: true });
    await writeFile(target, content);
  }
}

if (check && stale.length > 0) {
  console.error(
    `Schema reference pages are stale:\n${stale.map((file) => `  - ${file}`).join("\n")}\nRun \`pnpm schemas:generate\`.`,
  );
  process.exit(1);
}
console.log(
  check
    ? `[schema-reference] ${files.size} pages are up to date`
    : `[schema-reference] ${stale.length} of ${files.size} pages written`,
);
